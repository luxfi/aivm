// aivm_gpu_engine_wgpu.cpp — WebGPU/WGSL driver for AIVMGPUEngine.
//
// Produces byte-identical roots to the CPU oracle and the Metal/CUDA backends
// by running the WGSL kernels in aivm_*.wgsl through a real WebGPU runtime
// (Dawn or wgpu-native — both expose the same `webgpu/webgpu.h` C ABI).
//
// Build: enabled by `LUX_AIVM_ENABLE_WGPU=ON`. The CMakeLists locates the
// runtime via find_path(webgpu.h) + find_library(wgpu_native|wgpu) and
// defines LUX_AIVM_HAS_WEBGPU when both are present. If the runtime is not
// available, this file compiles to a no-op factory that returns nullptr —
// tests then exercise the CPU-only path.
//
// Lifecycle notes:
//   * One persistent (Instance, Adapter, Device, Queue) — created lazily in
//     create_aivm_gpu_engine_wgpu().
//   * Per round: arena buffers (storage), op buffers (storage), uniform
//     buffers (count vec4u), result buffer (storage) + map-read staging.
//   * Each of the four kernels has a dedicated ShaderModule + Pipeline +
//     BindGroupLayout (extracted via wgpuComputePipelineGetBindGroupLayout
//     so the layout is auto-derived from the WGSL declarations).
//   * Kernels run with workgroup_size(1) and dispatchWorkgroups(1,1,1) —
//     this matches the CPU oracle's strict sequential semantics, which is
//     load-bearing for byte-equal cross-backend determinism.
//   * Drain async work via wgpuInstanceProcessEvents (modern API) and
//     wgpuDevicePoll (wgpu-native extension) — both safe to call.

