// Workgroup constants must match the CUDA driver — kernels run serially
// (workgroup_size(1)), so the GPU produces the same insertion order as the
// CPU oracle even though the underlying hardware is parallel.
constexpr uint32_t kAttSlots       = kDefaultAttestationSlots;
constexpr uint32_t kModelSlots     = kDefaultModelSlots;
constexpr uint32_t kAnchorSlots    = kDefaultAnchorSlots;
constexpr uint32_t kMaxOpsPerRound = 4096u;

// 16-byte uniform: vec4<u32>. We pass per-arena counts in slot .x and zero
// elsewhere — matches `var<uniform> *_count_u: vec4<u32>` in the WGSL.
struct alignas(16) CountVec4 {
    uint32_t x = 0, y = 0, z = 0, w = 0;
};
static_assert(sizeof(CountVec4) == 16, "CountVec4 layout drift");

// Helpers --------------------------------------------------------------------

inline WGPUStringView sv(const char* s) {
    WGPUStringView v{};
    v.data = s;
    v.length = s == nullptr ? 0 : std::strlen(s);
    return v;
}
inline WGPUStringView sv(const std::string& s) {
    WGPUStringView v{};
    v.data = s.data();
    v.length = s.size();
    return v;
}

// Drive forward all in-flight async work. Both modern `webgpu.h` and the
// wgpu-native extension `wgpu.h` expose drainage; call both when available.
void drain(WGPUInstance instance, WGPUDevice device) {
    if (instance != nullptr) wgpuInstanceProcessEvents(instance);
#if defined(LUX_AIVM_HAS_WGPU_NATIVE)
    if (device != nullptr) wgpuDevicePoll(device, /*wait=*/WGPU_TRUE, nullptr);
#else
    (void)device;
#endif
}

// Block-on-buffer-map: returns true if the buffer is mapped successfully.
bool wait_map(WGPUInstance instance, WGPUDevice device,
              WGPUBuffer buffer, WGPUMapMode mode, size_t offset, size_t size)
{
    struct State {
        std::atomic<bool> done{false};
        WGPUMapAsyncStatus status{WGPUMapAsyncStatus_Error};
    } state;

    WGPUBufferMapCallbackInfo cb{};
    cb.mode = WGPUCallbackMode_AllowProcessEvents;
    cb.callback = [](WGPUMapAsyncStatus s, WGPUStringView /*msg*/,
                     void* u1, void* /*u2*/) {
        auto* st = static_cast<State*>(u1);
        st->status = s;
        st->done.store(true, std::memory_order_release);
    };
    cb.userdata1 = &state;
    cb.userdata2 = nullptr;

    WGPUFuture fut = wgpuBufferMapAsync(buffer, mode, offset, size, cb);
    (void)fut;
    for (int spin = 0; spin < 1024; ++spin) {
        if (state.done.load(std::memory_order_acquire)) break;
        drain(instance, device);
    }
    return state.done.load() && state.status == WGPUMapAsyncStatus_Success;
}

